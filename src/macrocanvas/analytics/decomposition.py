"""Accounting decomposition of the IS curve.

Because the synthetic output gap is generated by a known linear equation, its
components add up exactly.  This is an accounting decomposition, not an
orthogonalised historical shock decomposition: endogenous components such as
the real rate are themselves outcomes of the model.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from macrocanvas.config import ModelParameters

COMPONENT_COLUMNS = (
    "inertia",
    "real_rate",
    "fiscal",
    "external",
    "financial",
    "shock",
)
COMPONENT_LABELS = {
    "inertia": "Инерция выпуска",
    "real_rate": "Реальная ставка",
    "fiscal": "Фискальный импульс",
    "external": "Внешний спрос",
    "financial": "Финансовые условия",
    "shock": "Шок спроса",
}


def decompose_output_gap(
    data: pd.DataFrame,
    parameters: ModelParameters,
) -> pd.DataFrame:
    """Return exact contributions to the output gap, in percentage points."""
    required = {
        "output_gap",
        "real_rate_ex_ante",
        "fiscal_impulse",
        "external_demand_gap",
        "financial_stress",
    }
    missing = required - set(data.columns)
    if missing:
        raise ValueError(f"Missing columns for decomposition: {sorted(missing)}")
    p = parameters
    frame = pd.DataFrame(index=data.index)
    frame["inertia"] = p.output_gap_persistence * data["output_gap"].shift(1)
    frame["real_rate"] = -p.real_rate_sensitivity * (
        data["real_rate_ex_ante"] - p.neutral_real_rate
    )
    frame["fiscal"] = p.fiscal_impulse_effect * data["fiscal_impulse"]
    frame["external"] = p.external_demand_effect * data["external_demand_gap"]
    frame["financial"] = -p.financial_stress_effect * data["financial_stress"]
    # Exact innovation from the structural equation.  Computing it as a
    # residual makes the identity transparent and robust to future changes in
    # how shocks are stored.
    frame["shock"] = data["output_gap"] - frame[
        ["inertia", "real_rate", "fiscal", "external", "financial"]
    ].sum(axis=1)
    frame["sum"] = frame[list(COMPONENT_COLUMNS)].sum(axis=1)
    frame["output_gap"] = data["output_gap"]
    frame["identity_error"] = frame["sum"] - frame["output_gap"]
    # The first retained quarter requires burn-in history and is omitted from
    # the accounting figure.
    return frame.iloc[1:].copy()


def contribution_table(decomposition: pd.DataFrame) -> pd.DataFrame:
    """Long-format contribution table for plotting and export."""
    long = (
        decomposition[list(COMPONENT_COLUMNS)]
        .rename(columns=COMPONENT_LABELS)
        .reset_index()
        .melt(id_vars="quarter", var_name="component", value_name="contribution")
    )
    return long


def latest_waterfall(decomposition: pd.DataFrame) -> pd.DataFrame:
    """Contributions for the final quarter, ordered by magnitude."""
    latest = decomposition.iloc[-1]
    frame = (
        latest[list(COMPONENT_COLUMNS)]
        .rename(index=COMPONENT_LABELS)
        .to_frame("contribution")
    )
    frame["absolute"] = frame["contribution"].abs()
    frame = frame.sort_values("absolute", ascending=True)
    frame["cumulative_before"] = 0.0
    running = 0.0
    for label in frame.index:
        frame.loc[label, "cumulative_before"] = running
        running += frame.loc[label, "contribution"]
    frame["cumulative_after"] = frame["cumulative_before"] + frame["contribution"]
    return frame


def contribution_summary(decomposition: pd.DataFrame) -> pd.DataFrame:
    """Variance, standard deviation and extrema of each contribution."""
    rows = []
    for component in COMPONENT_COLUMNS:
        series = decomposition[component]
        rows.append(
            {
                "component": COMPONENT_LABELS[component],
                "mean": float(series.mean()),
                "std": float(series.std(ddof=1)),
                "min": float(series.min()),
                "max": float(series.max()),
                "max_abs": float(series.abs().max()),
                "identity_rmse": float(
                    np.sqrt(np.mean(decomposition["identity_error"] ** 2))
                ),
            }
        )
    return pd.DataFrame(rows)
